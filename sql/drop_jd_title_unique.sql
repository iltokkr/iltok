-- =====================================================================
-- jd.title 전역 UNIQUE 제약(jd_title_key) 제거
-- =====================================================================
-- 이유:
--   채용공고 제목은 서로 다른 업체가 동일하게 쓸 수 있어야 한다
--   (예: "포장사원 모집"). 그런데 jd.title 에 전역 UNIQUE 제약이 걸려 있어
--   두 번째 업체의 동일 제목 등록이 조용히 실패하는 잠재 버그였다.
--   (현재 데이터에 중복 title 0건 = 지금까지 중복 시도가 전부 막혀 온 방증)
--
--   의도된 중복 방지 규칙은 앱이 이미 처리한다:
--   writeComponent.tsx — "같은 광고주(uploader_id)가 같은 제목+지역" 재등록 차단.
--   따라서 전역 UNIQUE 제약은 불필요하며 정상 사용자를 막는다.
--
--   또한 이 제약은 대량 UPDATE(백필) 시 title 인덱스 재검증을 유발해
--   RLS 마이그레이션 백필을 막았던 원인이기도 하다.
--
-- 실행 위치: Supabase 대시보드 > SQL Editor
-- 롤백: ALTER TABLE public.jd ADD CONSTRAINT jd_title_key UNIQUE (title);
--       (단, 재추가하려면 중복 title 이 없어야 함)
-- =====================================================================

ALTER TABLE public.jd DROP CONSTRAINT IF EXISTS jd_title_key;
